import type { INodeProperties } from 'n8n-workflow';

const show = (resource: string, operation?: string[]) => ({
	show: { resource: [resource], ...(operation ? { operation } : {}) },
});

const ops = (resource: string, options: Array<[string, string, string]>, def: string): INodeProperties => ({
	displayName: 'Operation',
	name: 'operation',
	type: 'options',
	noDataExpression: true,
	displayOptions: show(resource),
	options: options.map(([name, value, action]) => ({ name, value, action, description: action })),
	default: def,
});

const json = (
	displayName: string,
	name: string,
	resource: string,
	operation: string[],
	def: string,
	description: string,
	required = false,
): INodeProperties => ({
	displayName,
	name,
	type: 'json',
	required,
	default: def,
	description,
	displayOptions: show(resource, operation),
});

